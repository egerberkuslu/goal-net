"""State layout, constants and spec tables, loaded from python/layout.json.

Nothing in this module is typed by hand. layout.json is generated by
``node python/tools/dump-layout.mjs`` straight out of packages/core and
packages/bots, so a field that moves on the JS side moves here on the next
regeneration instead of silently becoming a wrong offset.

What IS asserted here is the shape the port depends on: the ball sharing the
x/z/vx/vz prefix with a player, the stride being wide enough, the header words
the port reads by name. A layout change the port has not been taught about
fails at import rather than at tick 1743.

The three private flag bits (FLAG_TOUCHING / FLAG_TACKLE_HELD / FLAG_DIVE_HELD)
are the only values not available from a JS export -- world.js keeps them
module-private. They are 1, 2 and 4, checked against the JS source text by
test_parity.py so a renumbering there cannot pass unnoticed.
"""

