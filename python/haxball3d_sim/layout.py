def state_length(player_count: int) -> int:
    return PLAYER_BASE + player_count * PLAYER_STRIDE


def player_offset(i: int) -> int:
    return PLAYER_BASE + i * PLAYER_STRIDE


def _assert_shape() -> None:
    if not (P_X == 0 and P_Z == 1 and P_VX == 2 and P_VZ == 3):
        raise RuntimeError(
            "layout: the core no longer lays out x,z,vx,vz as the first four "
            "slots; every ball read in world.py assumes it does"
        )
    if BALL_BASE != HDR_LEN or PLAYER_BASE != BALL_BASE + BALL_LEN:
        raise RuntimeError("layout: header/ball/player bases are not contiguous")
    if PLAYER_STRIDE < max(FIELD.values()) + 1:
        raise RuntimeError("layout: player stride is smaller than the highest slot")
    if STATE_VERSION != 3:
        raise RuntimeError(
            f"layout: state version {STATE_VERSION} is not the v3 layout this port "
            "was written against; re-read world.js before regenerating"
        )
    missing = [
        k
        for k in (
            "KICK",
            "CHARGE",
            "CANCEL",
            "TACKLE",
            "CATCH",
            "THROW",
            "CLEAR",
            "DIVE",
            "TOUCH",
        )
        if k not in BTN
    ]
    if missing:
        raise RuntimeError(f"layout: BTN is missing {missing}")


_assert_shape()
